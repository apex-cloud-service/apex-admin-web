/**
 * 上传性别路由参数映射
 * ------------------------------------------------------------------
 * 用途：统一把调用方的性别枚举转换为文件服务 multipart 表单要求的
 * 字符串值。API 封装与两个上传组件（Element Plus 直传、增强组件的
 * XHR）共四条上传路径均经由本函数，避免各处硬编码映射漂移。
 */
/**
 * 把调用方的性别枚举映射为文件服务表单值
 *
 * 调用方口径为 0=AM、1=AF；文件服务的 multipart 表单 sex 字段要求
 * '1'=AM、'2'=AF，不能直接把调用方数值转为字符串发送。
 *
 * @param sex 调用方性别枚举（0=男/AM，1=女/AF）
 * @returns 文件服务表单值（'1'=AM，'2'=AF）
 */
export function toMultipartUploadSex(sex: 0 | 1): '1' | '2' {
  return sex === 0 ? '1' : '2'
}
